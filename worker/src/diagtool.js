export const LEVELS = [[80, 'متقدم', 'ok'], [60, 'متوسط', 'info'], [40, 'ناشئ', 'warn'], [0, 'يحتاج تدخلاً', 'bad']];
export const level = (s) => (s == null ? null : LEVELS.find((l) => s >= l[0]));

// الدرجة: لكل محور (مجموع الوزن × الإجابة) ÷ (مجموع الوزن × 3) للعبارات المجابة غير «لا ينطبق»؛ الإجمالي متوسط المحاور.
// الفجوة: إجابة 0 أو 1، وخطورتها الوزن × (3 − الإجابة)؛ والحرجة فجوة لعبارة لها نوع تعثر بإجابة 0.
export function score(tool, answers) {
  answers = answers || {};
  let all = 0, done = 0;
  const axes = tool.axes.map((a) => {
    let num = 0, den = 0, n = 0;
    for (const it of a.items) {
      all++;
      const x = answers[it.id], v = x && x.v;
      if (v === 'na') { done++; continue; }
      if (typeof v !== 'number') continue;
      done++; n++; num += it.w * v; den += it.w * 3;
    }
    return { id: a.id, s: den ? Math.round((num * 100) / den) : null, n, of: a.items.length };
  });
  const got = axes.filter((a) => a.s != null);
  const total = got.length ? Math.round(got.reduce((t, a) => t + a.s, 0) / got.length) : null;
  const gaps = [];
  for (const a of tool.axes) for (const it of a.items) {
    const x = answers[it.id], v = x && x.v;
    if (v === 0 || v === 1) gaps.push({ id: it.id, ax: a.id, v, sev: it.w * (3 - v), crit: !!(it.crit && v === 0) });
  }
  gaps.sort((p, q) => (q.crit - p.crit) || (q.sev - p.sev));
  return { total, axes, gaps, cov: all ? Math.round((done * 100) / all) : 0 };
}
