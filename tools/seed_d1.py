#!/usr/bin/env python3
"""Generate idempotent D1 seed SQL from the repo data files.

  python3 tools/seed_d1.py            -> seed/01_lookups.sql, seed/02_associations_NN.sql

Sources: data/public.json (public fields) + data/internal.redacted.json (licence dates
and registry status only). Contact / personal fields are NEVER read or written here.
Re-running is safe: rows are upserted by primary key.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)

GOV_ORDER = ['أبها', 'خميس مشيط', 'بيشة', 'النماص', 'محايل عسير', 'سراة عبيدة', 'رجال ألمع', 'تثليث', 'أحد رفيدة',
             'ظهران الجنوب', 'بلقرن', 'المجاردة', 'تنومة', 'طريب', 'البرك', 'بارق', 'الأمواه', 'الحرجة', 'الفرشة']


def q(v):
    if v is None or v == '':
        return 'NULL'
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def short(k):
    k = k.replace('للترفية', 'للترفيه')
    if k.startswith('وزارة '):
        k = k[6:]
    return {'المركز الوطني لتنمية القطاع غير الربحي': 'المركز الوطني للقطاع غير الربحي',
            'مدينة الملك عبدالعزيز للعلوم والتقنية': 'كاكست — العلوم والتقنية'}.get(k, k)


def main(batch=100):
    pub = json.load(open(P('data', 'public.json'), encoding='utf8'))
    internal = {r[0]: r for r in json.load(open(P('data', 'internal.redacted.json'), encoding='utf8'))['internal']}

    govs = sorted({a['gov'] for a in pub}, key=lambda g: (GOV_ORDER.index(g) if g in GOV_ORDER else 99, g))
    sups = sorted({a['sup'].replace('للترفية', 'للترفيه') for a in pub})
    gid = {g: i + 1 for i, g in enumerate(govs)}
    sid = {s: i + 1 for i, s in enumerate(sups)}

    fields, fid = [], {}
    def field(level, name, parent):
        key = (level, name, parent)
        if key not in fid:
            fid[key] = len(fields) + 1
            fields.append((fid[key], parent, level, name))
        return fid[key]
    for a in pub:
        f1 = field(1, a['grp'], None)
        f2 = field(2, a['s1'], f1)
        a['_field'] = field(3, a['s2'], f2)

    os.makedirs(P('seed'), exist_ok=True)
    L = ['-- generated by tools/seed_d1.py — do not edit by hand']
    L.append('INSERT INTO governorates (id, name_ar, sort) VALUES\n' + ',\n'.join(
        f'  ({gid[g]}, {q(g)}, {i})' for i, g in enumerate(govs)) +
        '\nON CONFLICT(id) DO UPDATE SET name_ar=excluded.name_ar, sort=excluded.sort;')
    L.append('INSERT INTO supervisors (id, name_ar, short_ar, sort) VALUES\n' + ',\n'.join(
        f'  ({sid[s]}, {q(s)}, {q(short(s))}, {i})' for i, s in enumerate(sups)) +
        '\nON CONFLICT(id) DO UPDATE SET name_ar=excluded.name_ar, short_ar=excluded.short_ar;')
    L.append('INSERT INTO fields (id, parent_id, level, name_ar) VALUES\n' + ',\n'.join(
        f'  ({i}, {q(p)}, {lv}, {q(n)})' for i, p, lv, n in fields) +
        '\nON CONFLICT(id) DO UPDATE SET parent_id=excluded.parent_id, level=excluded.level, name_ar=excluded.name_ar;')
    open(P('seed', '01_lookups.sql'), 'w', encoding='utf8').write('\n\n'.join(L) + '\n')

    rows = []
    for a in pub:
        r = internal.get(a['id'])
        founded, issued, exp, st = (r[9], r[10], r[11], r[13]) if r else (f"{a['y']}-01-01" if a.get('y') else None, None, None, 'مفعل')
        rows.append(f"  ({a['id']}, {q(a['n'])}, {q(a['lic'])}, {gid[a['gov']]}, {sid[a['sup'].replace('للترفية', 'للترفيه')]}, "
                    f"{a['_field']}, {q(founded)}, {q(issued)}, {q(exp)}, {q(st or 'مفعل')})")
    files = []
    for n in range(0, len(rows), batch):
        f = P('seed', f'02_associations_{n // batch + 1:02d}.sql')
        open(f, 'w', encoding='utf8').write(
            '-- generated by tools/seed_d1.py\nINSERT INTO associations (id, name_ar, license_no, governorate_id, supervisor_id, '
            'field_id, founded_on, license_issued_on, license_expires_on, registry_status) VALUES\n' + ',\n'.join(rows[n:n + batch]) +
            '\nON CONFLICT(id) DO UPDATE SET name_ar=excluded.name_ar, license_no=excluded.license_no, '
            'governorate_id=excluded.governorate_id, supervisor_id=excluded.supervisor_id, field_id=excluded.field_id, '
            'founded_on=excluded.founded_on, license_issued_on=excluded.license_issued_on, '
            'license_expires_on=excluded.license_expires_on, registry_status=excluded.registry_status, '
            "updated_at=strftime('%Y-%m-%dT%H:%M:%SZ','now');\n")
        files.append(f)
    print(f'{len(govs)} governorates, {len(sups)} supervisors, {len(fields)} fields, {len(rows)} associations -> seed/ ({len(files)} files)')


if __name__ == '__main__':
    main()
